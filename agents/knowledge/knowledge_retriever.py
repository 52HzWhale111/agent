# ========== 检索逻辑 ==========

def retrieve(question: str, top_k: int = 3) -> List[Dict]:
    """
    检索最相关的知识点（中文关键词匹配版）
    :param question: 学生的问题
    :param top_k: 返回最相关的几条
    :return: 知识点列表，按相关度排序
    """
    question_clean = re.sub(r'[^\w\s]', '', question)  # 去掉标点
    scored = []

    for kp in KNOWLEDGE_BASE:
        score = 0

        # 1. 关键词匹配：每个出现在问题里的关键词加2分
        for kw in kp.get("keywords", []):
            if kw in question_clean:
                score += 2

        # 2. 标题匹配：标题中的词出现在问题里，加3分
        title_clean = kp["title"].replace("（", "(").replace("）", ")")
        # 把标题拆成几个部分来匹配（简单按括号、空格拆分）
        title_parts = re.split(r'[()\s\-:：]', title_clean)
        for part in title_parts:
            part = part.strip()
            if len(part) >= 2 and part in question_clean:
                score += 3

        # 3. 定义匹配：定义里的重要词出现在问题里，加1分
        # 简单取定义里长度>=3的中文词组
        def_words = re.findall(r'[\u4e00-\u9fa5]{3,}', kp["definition"])
        for w in def_words:
            if w in question_clean:
                score += 1

        if score > 0:
            scored.append((score, kp))

    scored.sort(key=lambda x: x[0], reverse=True)
    return [kp for score, kp in scored[:top_k]]


def format_for_prompt(retrieved_kps: List[Dict]) -> str:
    """把检索到的知识点格式化成Prompt里的参考资料格式"""
    result = []
    for kp in retrieved_kps:
        result.append(f"""
【{kp['kp_id']} {kp['title']}】
定义：{kp['definition']}
例子：{kp['example']}
出处：{kp['chapter']}
""")
    return "\n".join(result)


